
public class Var02 {
	public static void main(String[] args) {
		
		// 1.1 정수형
		// int (default)
		
		byte a = (byte) 128;
		System.out.println(a);
		
		long b = 21000000000L;
		System.out.println(b);
		
		// 1.2 실수형(소수점 있는 숫자)
		// 보통 double(default)
		
		float eyeSight = 0.6f;
		System.out.println(eyeSight);
		
		double weight = 50.8;
		System.out.println(weight);
		
		// 1.3 문자형 (한 글자)
		
		char gender = 'M';
		System.out.println(gender);
		
		// 1.4 논리형 (참/거짓) true, false
		
		boolean soldOut = false;
		System.out.println(soldOut);
		
		boolean stock = true;
		System.out.println(stock);
		
		int c = 10;
		int d = 20;
		int e,f,g;
		e = 1;
		f = 2;
		g = 3;
		System.out.println(g);
		
		boolean judge = c < f;
		System.out.println(judge);
		
		// 3. 아무것도 없다 void
		
		
	}
}
